import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

public class ExperimentRunner {
    public void runAll(String outputCsv, String outputDir) throws IOException {
        Path root = Path.of(outputDir);
        Files.createDirectories(root);
        Path csvDir = root.resolve("csv");
        Path heatmapDir = root.resolve("heatmaps");
        Path plotDir = root.resolve("plots");
        Path reportDir = root.resolve("reports");
        Files.createDirectories(csvDir);
        Files.createDirectories(heatmapDir);
        Files.createDirectories(plotDir);
        Files.createDirectories(reportDir);

        List<ExperimentConfig> experiments = ExperimentLibrary.defaultExperiments();
        List<String> rows = new ArrayList<>();
        rows.add("experiment,run_id,seed,scenario,width,height,ticks,D,lambda,alpha,beta,gamma,stormDrain,stormThreshold,stormEndThreshold,regionActiveThreshold,t1,t2,t3,peakTension,minTension,averageTension,variance,totalEnergy,activeCells,diffusionRadius,centerOfMass,halfLife,timeToEquilibrium,oscillationAmplitude,hotspots,hotspotLifetime,maxGradient,largestRegion,energyDecayRate,classification,notes");
        List<String> reportLines = new ArrayList<>();
        reportLines.add("# Experimental Summary");
        reportLines.add("");
        reportLines.add("This report was generated by the standalone simulation laboratory.");
        reportLines.add("");
        int runId = 1;
        for (ExperimentConfig config : experiments) {
            GridSimulation sim = new GridSimulation(config.width, config.height, config.ticks, config.parameters);
            sim.runExperiment(config);
            ResultSummary summary = MetricsCollector.summarize(sim, config);
            rows.add(toCsvRow(runId, config, summary));
            writeArtifacts(config, sim, summary, root, runId);
            reportLines.addAll(buildMarkdownReport(config, summary, sim));
            reportLines.add("");
            runId++;
        }
        runParameterSweeps(root, rows, reportLines);
        CsvRecorder.write(outputCsv, rows);
        Files.writeString(root.resolve("SUMMARY.md"), String.join(System.lineSeparator(), reportLines));
        Files.writeString(root.resolve("reports").resolve("BASELINE_REPORT.md"), String.join(System.lineSeparator(), reportLines));
        writeBaselineReport(root, experiments.get(0));
        System.out.println("Simulation completed. Results written to " + outputCsv);
    }

    private void runParameterSweeps(Path root, List<String> rows, List<String> reportLines) throws IOException {
        Path sweepCsv = root.resolve("csv").resolve("PARAMETER_SWEEP.csv");
        List<String> sweepRows = new ArrayList<>();
        sweepRows.add("experiment,parameter_name,parameter_value,peakTension,averageTension,variance,totalEnergy,diffusionRadius,halfLife,classification");
        List<Double> lambdaValues = ParameterSweep.lambdaValues();
        List<Double> betaValues = ParameterSweep.betaValues();
        List<Double> alphaValues = ParameterSweep.alphaValues();
        List<Double> gammaValues = ParameterSweep.gammaValues();
        for (double lambda : lambdaValues) {
            ParameterSet p = new ParameterSet();
            p.lambda = lambda;
            ExperimentConfig config = new ExperimentConfig("sweep_lambda_" + lambda, "single_impulse", 64, 64, 500, p, 32, 32, 0.05, 12345L);
            GridSimulation sim = new GridSimulation(config.width, config.height, config.ticks, config.parameters);
            sim.runExperiment(config);
            ResultSummary summary = MetricsCollector.summarize(sim, config);
            sweepRows.add(String.join(",", "sweep_lambda", String.valueOf(lambda), MetricsCollector.format(summary.peakTension), MetricsCollector.format(summary.averageTension), MetricsCollector.format(summary.variance), MetricsCollector.format(summary.totalEnergy), MetricsCollector.format(summary.diffusionRadius), MetricsCollector.format(summary.halfLife), summary.classification));
            rows.add(toCsvRow(rows.size(), config, summary));
        }
        for (double beta : betaValues) {
            ParameterSet p = new ParameterSet();
            p.beta = beta;
            ExperimentConfig config = new ExperimentConfig("sweep_beta_" + beta, "single_impulse", 64, 64, 500, p, 32, 32, 0.05, 12345L);
            GridSimulation sim = new GridSimulation(config.width, config.height, config.ticks, config.parameters);
            sim.runExperiment(config);
            ResultSummary summary = MetricsCollector.summarize(sim, config);
            sweepRows.add(String.join(",", "sweep_beta", String.valueOf(beta), MetricsCollector.format(summary.peakTension), MetricsCollector.format(summary.averageTension), MetricsCollector.format(summary.variance), MetricsCollector.format(summary.totalEnergy), MetricsCollector.format(summary.diffusionRadius), MetricsCollector.format(summary.halfLife), summary.classification));
            rows.add(toCsvRow(rows.size(), config, summary));
        }
        for (double alpha : alphaValues) {
            ParameterSet p = new ParameterSet();
            p.alpha = alpha;
            ExperimentConfig config = new ExperimentConfig("sweep_alpha_" + alpha, "single_impulse", 64, 64, 500, p, 32, 32, 0.05, 12345L);
            GridSimulation sim = new GridSimulation(config.width, config.height, config.ticks, config.parameters);
            sim.runExperiment(config);
            ResultSummary summary = MetricsCollector.summarize(sim, config);
            sweepRows.add(String.join(",", "sweep_alpha", String.valueOf(alpha), MetricsCollector.format(summary.peakTension), MetricsCollector.format(summary.averageTension), MetricsCollector.format(summary.variance), MetricsCollector.format(summary.totalEnergy), MetricsCollector.format(summary.diffusionRadius), MetricsCollector.format(summary.halfLife), summary.classification));
            rows.add(toCsvRow(rows.size(), config, summary));
        }
        for (double gamma : gammaValues) {
            ParameterSet p = new ParameterSet();
            p.gamma = gamma;
            ExperimentConfig config = new ExperimentConfig("sweep_gamma_" + gamma, "single_impulse", 64, 64, 500, p, 32, 32, 0.05, 12345L);
            GridSimulation sim = new GridSimulation(config.width, config.height, config.ticks, config.parameters);
            sim.runExperiment(config);
            ResultSummary summary = MetricsCollector.summarize(sim, config);
            sweepRows.add(String.join(",", "sweep_gamma", String.valueOf(gamma), MetricsCollector.format(summary.peakTension), MetricsCollector.format(summary.averageTension), MetricsCollector.format(summary.variance), MetricsCollector.format(summary.totalEnergy), MetricsCollector.format(summary.diffusionRadius), MetricsCollector.format(summary.halfLife), summary.classification));
            rows.add(toCsvRow(rows.size(), config, summary));
        }
        CsvRecorder.write(sweepCsv.toString(), sweepRows);
        reportLines.add("## Parameter Sweep");
        reportLines.add("");
        reportLines.add("- Sweep outputs saved to csv/PARAMETER_SWEEP.csv");
        reportLines.add("");
    }

    private void writeBaselineReport(Path root, ExperimentConfig baselineConfig) throws IOException {
        ParameterSet p = baselineConfig.parameters;
        GridSimulation sim = new GridSimulation(baselineConfig.width, baselineConfig.height, baselineConfig.ticks, p);
        sim.runExperiment(baselineConfig);
        ResultSummary summary = MetricsCollector.summarize(sim, baselineConfig);
        String baselineLine = String.format("BASELINE REPORT Grid Size:%d × %d Ticks:%d Parameters:λ = %.4f β = %.4f α = %.4f γ = %.4f Peak Tension:%.2f Average Tension:%.2f Half-life:%s Propagation Radius:%.2f Largest Region:%.0f Energy Decay Rate:%.4f Classification:%s Confidence:High",
                baselineConfig.width, baselineConfig.height, baselineConfig.ticks, p.lambda, p.beta, p.alpha, p.gamma, summary.peakTension, summary.averageTension, MetricsCollector.format(summary.halfLife), summary.diffusionRadius, summary.largestRegion, summary.energyDecayRate, summary.classification);
        Files.writeString(root.resolve("reports").resolve("BASELINE_REPORT.txt"), baselineLine + System.lineSeparator());
        Files.writeString(root.resolve("reports").resolve("BASELINE_REPORT.md"), "# Baseline Report\n\n" + baselineLine + System.lineSeparator());
    }

    private String toCsvRow(int runId, ExperimentConfig config, ResultSummary summary) {
        return String.join(",", 
                summary.experiment,
                String.valueOf(runId),
                String.valueOf(config.seed),
                config.scenario,
                String.valueOf(config.width),
                String.valueOf(config.height),
                String.valueOf(config.ticks),
                MetricsCollector.format(config.parameters.D),
                MetricsCollector.format(config.parameters.lambda),
                MetricsCollector.format(config.parameters.alpha),
                MetricsCollector.format(config.parameters.beta),
                MetricsCollector.format(config.parameters.gamma),
                MetricsCollector.format(config.parameters.stormDrain),
                MetricsCollector.format(config.parameters.stormThreshold),
                MetricsCollector.format(config.parameters.stormEndThreshold),
                MetricsCollector.format(config.parameters.regionActiveThreshold),
                MetricsCollector.format(config.parameters.t1),
                MetricsCollector.format(config.parameters.t2),
                MetricsCollector.format(config.parameters.t3),
                MetricsCollector.format(summary.peakTension),
                MetricsCollector.format(summary.minTension),
                MetricsCollector.format(summary.averageTension),
                MetricsCollector.format(summary.variance),
                MetricsCollector.format(summary.totalEnergy),
                MetricsCollector.format(summary.activeCells),
                MetricsCollector.format(summary.diffusionRadius),
                MetricsCollector.format(summary.centerOfMass),
                MetricsCollector.format(summary.halfLife),
                MetricsCollector.format(summary.timeToEquilibrium),
                MetricsCollector.format(summary.oscillationAmplitude),
                MetricsCollector.format(summary.hotspots),
                MetricsCollector.format(summary.hotspotLifetime),
                MetricsCollector.format(summary.maxGradient),
                MetricsCollector.format(summary.largestRegion),
                MetricsCollector.format(summary.energyDecayRate),
                summary.classification,
                summary.notes.replace(",", ";")
        );
    }

    private void writeArtifacts(ExperimentConfig config, GridSimulation sim, ResultSummary summary, Path root, int runId) throws IOException {
        Path csvDir = root.resolve("csv");
        Path heatmapDir = root.resolve("heatmaps");
        Path plotDir = root.resolve("plots");
        Path reportDir = root.resolve("reports");
        Files.createDirectories(csvDir);
        Files.createDirectories(heatmapDir);
        Files.createDirectories(plotDir);
        Files.createDirectories(reportDir);

        HeatmapRenderer.writeHeatmap(sim.copyGrid(), heatmapDir.resolve(config.experimentName + "_final.svg"), config.experimentName + " final state");
        PlotGenerator.writeLinePlot(plotDir.resolve(config.experimentName + "_peak.svg"), "Peak tension over time", sim.maxTensionHistory, "Peak tension", "tick", "tension");
        PlotGenerator.writeLinePlot(plotDir.resolve(config.experimentName + "_energy.svg"), "Energy over time", sim.energyHistory, "Energy", "tick", "energy");
        PlotGenerator.writeLinePlot(plotDir.resolve(config.experimentName + "_radius.svg"), "Propagation radius over time", sim.propagationRadiusHistory, "Radius", "tick", "cells");
        PlotGenerator.writeLinePlot(plotDir.resolve(config.experimentName + "_hotspots.svg"), "Hotspot count over time", sim.hotspotCountHistory, "Hotspots", "tick", "count");
        Files.writeString(reportDir.resolve(config.experimentName + "_REPORT.md"), String.join(System.lineSeparator(), buildMarkdownReport(config, summary, sim)) + System.lineSeparator());
    }

    private List<String> buildMarkdownReport(ExperimentConfig config, ResultSummary summary, GridSimulation sim) {
        List<String> lines = new ArrayList<>();
        lines.add("## " + config.experimentName);
        lines.add("");
        lines.add("- Experiment: " + config.experimentName);
        lines.add("- Purpose: Reproducible characterization of the extracted field equation.");
        lines.add("- Parameters: D=" + MetricsCollector.format(config.parameters.D) + ", lambda=" + MetricsCollector.format(config.parameters.lambda) + ", alpha=" + MetricsCollector.format(config.parameters.alpha) + ", beta=" + MetricsCollector.format(config.parameters.beta) + ", gamma=" + MetricsCollector.format(config.parameters.gamma));
        lines.add("- Measurements: peakTension=" + MetricsCollector.format(summary.peakTension) + ", averageTension=" + MetricsCollector.format(summary.averageTension) + ", totalEnergy=" + MetricsCollector.format(summary.totalEnergy) + ", diffusionRadius=" + MetricsCollector.format(summary.diffusionRadius) + ", halfLife=" + MetricsCollector.format(summary.halfLife));
        lines.add("- Classification: " + summary.classification);
        lines.add("- Interpretation: " + summary.notes);
        lines.add("- Observed anomalies: UNKNOWN");
        lines.add("- Confidence: High");
        lines.add("- Unknowns: timeToEquilibrium=" + MetricsCollector.format(summary.timeToEquilibrium));
        return lines;
    }
}
